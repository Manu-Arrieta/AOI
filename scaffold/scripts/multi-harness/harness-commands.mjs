/**
 * scripts/multi-harness/harness-commands.mjs
 *
 * Registers AOI's `/commands` natively in the harnesses that have a command
 * directory, so a slash command means the same thing wherever it is typed.
 *
 * WHY THIS EXISTS. `.github/prompts/` is GitHub Copilot's convention: Copilot
 * reads `*.prompt.md` and exposes each as `/name`. No other harness looks
 * there. AOI nonetheless compiled the command table into every dialect, so
 * CLAUDE.md documented a `/init` that Claude Code had never heard of.
 *
 * That was not merely inert. Claude Code ships its own bundled `/init`, whose
 * one deliverable is to write `CLAUDE.md` — the file AOI compiles with an
 * unconditional write and whose hand edits the `commit-msg` guard refuses. So
 * the single name `/init` reached two commands doing opposite things, and the
 * one that answered was the one that destroys its own output. `init` is the
 * only collision: checked against Claude Code's bundled set, every other AOI
 * prompt name is free.
 *
 * A project command outranks a bundled one, so writing `.claude/commands/init.md`
 * is what makes `/init` resolve to AOI's flow there, exactly as it already does
 * in Copilot.
 *
 * WHY A POINTER AND NOT A COPY. Copying each prompt's body would put the same
 * instructions in two files that nothing keeps equal — the drift Principle I
 * exists to refuse, reintroduced one directory over. The generated file names
 * the canonical prompt and stops; `.github/prompts/` stays the only source.
 */

import fs from 'node:fs'
import path from 'node:path'

/** Where the canonical prompts live. Copilot reads this directory directly. */
export const PROMPTS_DIR = '.github/prompts'

/**
 * Harnesses with a project command directory, and what they accept there.
 *
 * Absent on purpose:
 *   - `copilot` reads `.github/prompts/` natively; generating anything would
 *     duplicate what already works.
 *   - `cline` reads `.clinerules/workflows/`, but AOI writes `.clinerules` as a
 *     FILE. One path cannot be both, so wiring Cline means converting its
 *     adapter to a directory — a change to how every existing installation is
 *     laid out, and the Owner's call, not this module's.
 *   - `antigravity` has no command convention verified against its docs.
 *     Guessing a directory would ship dead files.
 */
export const COMMAND_TARGETS = {
  claude: { dir: '.claude/commands', frontmatter: true },
  cursor: { dir: '.cursor/commands', frontmatter: false },
}

/**
 * The prompt names available, without the `.prompt.md` suffix.
 *
 * @param {string} repoRoot
 * @returns {string[]}
 */
export function listPromptNames(repoRoot) {
  const dir = path.join(repoRoot, PROMPTS_DIR)
  if (!fs.existsSync(dir)) return []
  return fs
    .readdirSync(dir)
    .filter((file) => file.endsWith('.prompt.md'))
    .map((file) => file.slice(0, -'.prompt.md'.length))
    .sort()
}

/**
 * The `description` from a prompt's YAML frontmatter, or '' when it has none.
 *
 * Deliberately a line scan rather than a YAML parse: the frontmatter here is
 * two or three flat keys, and taking a dependency to read them would make the
 * compiler fail on a tree that has not installed one.
 *
 * @param {string} repoRoot
 * @param {string} name
 * @returns {string}
 */
export function readPromptDescription(repoRoot, name) {
  const file = path.join(repoRoot, PROMPTS_DIR, `${name}.prompt.md`)
  let content
  try {
    content = fs.readFileSync(file, 'utf8')
  } catch {
    return ''
  }

  const lines = content.split('\n')
  if (lines[0]?.trim() !== '---') return ''

  for (const line of lines.slice(1)) {
    if (line.trim() === '---') break
    const match = /^description:\s*(.*)$/.exec(line)
    if (match) return match[1].trim().replace(/^["']|["']$/g, '')
  }
  return ''
}

/**
 * The command file's body: a pointer at the canonical prompt.
 *
 * @param {{ name: string, description?: string, withFrontmatter?: boolean }} options
 * @returns {string}
 */
export function renderCommandPointer({ name, description = '', withFrontmatter = false }) {
  const promptPath = `${PROMPTS_DIR}/${name}.prompt.md`
  const head = withFrontmatter && description ? `---\ndescription: "${description.replace(/"/g, "'")}"\n---\n\n` : ''

  return `${head}# /${name}

<!-- Generated by \`pnpm aoi:sync-rules\`. Do not edit: the source is ${promptPath}. -->

Read \`${promptPath}\` in this repository and execute it exactly as written,
following every step in order.

That file is the single definition of this command for every assistant. This
pointer exists only so \`/${name}\` resolves here the same way it resolves in
GitHub Copilot, which reads \`${PROMPTS_DIR}\` natively.
`
}

/**
 * Writes one harness's command directory from the canonical prompts.
 *
 * @param {string} repoRoot
 * @param {(relPath: string, content: string) => void} writeTargetFile
 * @param {string} harness
 * @returns {string[]} the relative paths written
 */
export function syncHarnessCommands(repoRoot, writeTargetFile, harness) {
  const target = COMMAND_TARGETS[harness]
  if (!target) return []

  const written = []
  for (const name of listPromptNames(repoRoot)) {
    const relPath = `${target.dir}/${name}.md`
    writeTargetFile(
      relPath,
      renderCommandPointer({
        name,
        description: readPromptDescription(repoRoot, name),
        withFrontmatter: target.frontmatter,
      }),
    )
    written.push(relPath)
  }
  return written
}
