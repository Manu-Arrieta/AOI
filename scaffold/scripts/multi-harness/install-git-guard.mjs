// scripts/multi-harness/install-git-guard.mjs
//
// Wires `.githooks/pre-commit-aoi-guard.sh` as the repository's `commit-msg`
// hook, and audits that the wiring is actually REACHABLE.
//
// Why this module exists instead of the wiring staying in `setup.sh`: it lived
// there, inside the `PROFILE_INCLUDES_ADVANCED` branch, while the guard script
// itself is parity-governed and arrives through the scaffold merge in EVERY
// profile. A `core` install therefore received the guard and never wired it —
// an executable, documented, permanently inert guard. Measured on a real `core`
// install: `.git/hooks/commit-msg` absent, and `scripts/bin/aoi-copilot` — the
// one artifact in that branch with no governed counterpart — also absent. The
// guard's own error text tells the operator to "Reinstalar AOI", a remedy that
// cannot work, because a reinstall takes the same skipped branch.
//
// Wiring is a DELEGATING shim, never a copy of the guard. `setup.sh` used to
// `cp` the guard into place; on the next run its `grep -q
// "pre-commit-aoi-guard.sh"` matched that copy, reported "already chained
// (skipped)", and left a frozen duplicate of a file that IS updated on every
// reinstall. A shim that resolves the guard at run time has one code path and
// cannot go stale.
//
// Ported from `setup.sh` Phase 1.7 so that ONE owner wires the hook, and so the
// wiring is auditable by `aoi:hooks` — step 8 of `pnpm test`. A guard that
// nothing wires is worse than no guard: a surface loaded in every phase
// advertises it as automatic.

import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

/** Path of the guard inside the project, relative to its root. */
export const GUARD_RELATIVE = path.join('.githooks', 'pre-commit-aoi-guard.sh')

const HOOKS_DIR = path.join('.git', 'hooks')
const COMMIT_MSG = path.join(HOOKS_DIR, 'commit-msg')
const LEGACY_PRECOMMIT = path.join(HOOKS_DIR, 'pre-commit')
const BAK_SUFFIX = 'aoi-bak'

/** Identifies a hook file as AOI's own, so the Owner's own hook is never clobbered. */
const MARKER = 'pre-commit-aoi-guard.sh'

/** The shim, byte-identical to the chain `setup.sh` used to generate. */
const SHIM = `#!/usr/bin/env bash
# AOI bootstrap chain: run the guard, then delegate to the project commit-msg.
# Generated by scripts/multi-harness/install-git-guard.mjs — edit that module.
SELF_DIR="$(cd "$(dirname "$0")" && pwd)"
bash "$SELF_DIR/../../.githooks/pre-commit-aoi-guard.sh" "$@" || exit $?
if [ -f "$SELF_DIR/commit-msg.aoi-bak" ]; then
  exec bash "$SELF_DIR/commit-msg.aoi-bak" "$@"
fi
exit 0
`

function defaultExec(cmd, args) {
  return execFileSync(cmd, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim()
}

/**
 * Reads `core.hooksPath`. When it is set, git stops reading `.git/hooks/`
 * entirely — so a perfectly installed `commit-msg` there is inert. This is the
 * same failure mode one layer down, and the reason the audit does not stop at
 * "the file exists".
 */
export function readHooksPath(root, execFn = defaultExec) {
  try {
    return execFn('git', ['-C', root, 'config', '--get', 'core.hooksPath'])
  } catch {
    return ''
  }
}

/**
 * Whether this tree is an INSTALLED workspace rather than AOI's own development
 * repository, read from the install manifest `setup.sh` writes.
 *
 * The distinction is load-bearing, not cosmetic. The wiring lives under
 * `.git/hooks/`, which git never versions, so "the guard is wired" is a claim
 * only an installer can make and only an installer's tree can be held to.
 * Gating on it without this discriminator fails on every fresh clone and in CI,
 * and a gate that fails for a non-defect is one people learn to bypass.
 */
export function isInstalledWorkspace(root) {
  return fs.existsSync(path.join(root, '.conf', 'manifest.json'))
}

function readIfPresent(file) {
  try {
    return fs.readFileSync(file, 'utf8')
  } catch {
    return null
  }
}

function isExecutable(file) {
  try {
    fs.accessSync(file, fs.constants.X_OK)
    return true
  } catch {
    return false
  }
}

/**
 * Reports whether the guard is installed AND reachable. `reachable` is the
 * claim the prose in CLAUDE.md makes; the other fields say why when it is false.
 */
export function auditGitGuard(root, execFn = defaultExec) {
  const guard = path.join(root, GUARD_RELATIVE)
  const hook = path.join(root, COMMIT_MSG)
  const hookBody = readIfPresent(hook)
  const hooksPath = readHooksPath(root, execFn)

  const out = {
    gitRepo: fs.existsSync(path.join(root, '.git')),
    guardPresent: fs.existsSync(guard),
    guardExecutable: isExecutable(guard),
    hookPresent: hookBody !== null,
    hookExecutable: hookBody !== null && isExecutable(hook),
    hookReferencesGuard: hookBody !== null && hookBody.includes(MARKER),
    hooksPath,
    reachable: false,
  }
  out.reachable =
    out.gitRepo &&
    out.guardPresent &&
    out.guardExecutable &&
    out.hookPresent &&
    out.hookExecutable &&
    out.hookReferencesGuard &&
    !out.hooksPath
  return out
}

/**
 * Wires the guard. Idempotent, and safe to re-run: an existing `commit-msg`
 * written by anyone other than AOI is preserved as `<hook>.aoi-bak` and still
 * runs, by delegation, after the guard.
 *
 * @returns {{ changed: boolean, skipped: string, actions: string[] }}
 */
export function installGitGuard(root) {
  const actions = []
  if (!fs.existsSync(path.join(root, '.git'))) {
    return { changed: false, skipped: 'not a git repository', actions }
  }

  const hooksDir = path.join(root, HOOKS_DIR)
  fs.mkdirSync(hooksDir, { recursive: true })

  // Retire the `pre-commit` wiring a previous AOI left behind. Left in place it
  // blocks first, before `commit-msg` ever runs, so the `[aoi-managed-ok]`
  // override stays unreachable no matter how correct the new hook is. Only OUR
  // hook is touched: one the operator wrote is left exactly as it is.
  const legacy = path.join(root, LEGACY_PRECOMMIT)
  const legacyBody = readIfPresent(legacy)
  if (legacyBody !== null && legacyBody.includes(MARKER)) {
    const legacyBak = `${legacy}.${BAK_SUFFIX}`
    if (fs.existsSync(legacyBak)) {
      fs.renameSync(legacyBak, legacy)
      actions.push('restored the project pre-commit the guard had displaced')
    } else {
      fs.rmSync(legacy)
      actions.push('retired the guard from pre-commit (it moved to commit-msg)')
    }
  }

  const hook = path.join(root, COMMIT_MSG)
  const hookBody = readIfPresent(hook)

  // Preserve a hook AOI did not write. Replacing it wholesale would silently
  // drop whatever the Owner or another tool put there.
  if (hookBody !== null && !hookBody.includes(MARKER)) {
    const bak = `${hook}.${BAK_SUFFIX}`
    if (fs.existsSync(bak)) {
      fs.renameSync(bak, `${bak}.${new Date().toISOString().replace(/[-:]/g, '').split('.')[0]}Z`)
      actions.push('kept the previous commit-msg.aoi-bak under a timestamp')
    }
    fs.renameSync(hook, bak)
    actions.push('backed up the existing commit-msg')
  }

  const changed = hookBody !== SHIM
  if (changed) {
    fs.writeFileSync(hook, SHIM)
    actions.push('wrote the delegating commit-msg shim')
  }
  fs.chmodSync(hook, 0o755)

  return { changed, skipped: '', actions }
}

function main() {
  const root = process.cwd()

  if (process.argv.includes('--audit')) {
    const r = auditGitGuard(root)
    console.log('=== AOI Git Guard ===\n')
    if (!r.gitRepo) {
      console.log('  — no es un repo git: el guard se activa cuando corra git init.')
      return
    }
    console.log(`  ${r.guardPresent ? '✅' : '❌'} .githooks/pre-commit-aoi-guard.sh presente`)
    console.log(`  ${r.guardExecutable ? '✅' : '❌'} .githooks/pre-commit-aoi-guard.sh ejecutable`)
    console.log(`  ${r.hookPresent ? '✅' : '❌'} .git/hooks/commit-msg presente`)
    console.log(`  ${r.hookReferencesGuard ? '✅' : '❌'} .git/hooks/commit-msg invoca el guard`)
    if (r.hooksPath) console.error(`  ❌ core.hooksPath='${r.hooksPath}' — git NO lee .git/hooks/, el guard está inerte`)
    if (!r.reachable) {
      console.error('\nUn guard que nadie cablea es una regla que el Owner cree activa y no lo está.')
      process.exit(1)
    }
    console.log('\n✅ El guard está cableado como commit-msg y es alcanzable.')
    return
  }

  const r = installGitGuard(root)
  if (r.skipped) {
    console.log(`— Guard no cableado: ${r.skipped}`)
    return
  }
  console.log(r.changed ? `✅ Guard cableado → ${COMMIT_MSG}` : `✅ Guard ya cableado → ${COMMIT_MSG}`)
  for (const a of r.actions) console.log(`   · ${a}`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))) {
  main()
}
